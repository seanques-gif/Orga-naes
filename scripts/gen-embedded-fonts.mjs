// Embed the core UI fonts (IBM Plex Sans, IBM Plex Mono, Inter) directly into
// the app as base64 woff2 so typography is identical offline / on file:// and
// needs zero network at boot.
//
// Regenerate after an intentional font-mix change:
//   node scripts/gen-embedded-fonts.mjs
// The output is committed (src/styles/00-embedded-fonts.css), so this script
// is only needed when the font set itself changes.
import { writeFileSync } from 'fs';

// Modern-Chrome UA => Google serves woff2 with unicode-range subsetting.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const FAMILIES = [
  { css: 'IBM Plex Sans', url: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&display=swap' },
  { css: 'IBM Plex Mono', url: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;600&display=swap' },
  { css: 'Inter', url: 'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap' },
];
const comments = {
  400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold',
};

const css2 = async (url) => (await fetch(url, { headers: { 'User-Agent': UA } })).text();
const bin = async (url) => Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());

// Parse every /* subset */ @font-face block from a css2 response.
function parseBlocks(css) {
  const out = [];
  const re = /\/\* ([a-z-]+) \*\/\s*@font-face \{([\s\S]*?)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const subset = m[1];
    const body = m[2];
    const weight = (body.match(/font-weight: (\d+)/) || [])[1];
    const url = (body.match(/src: url\((\S+?)\) format\('woff2'\)/) || [])[1];
    const range = (body.match(/unicode-range: ([^;]+);/) || [])[1];
    if (subset && weight && url) out.push({ subset, weight, url, range });
  }
  return out;
}

let css = `/* EMBEDDED FONTS (generated by scripts/gen-embedded-fonts.mjs — do not edit)\n   IBM Plex Sans 400/500/600/700, IBM Plex Mono 400/600, Inter 400/500/600/700.\n   Latin subsets only, base64 woff2, font-display: swap. This must load FIRST\n   so the faces exist before any component CSS resolves. */\n`;
let bytes = 0, faces = 0;
for (const fam of FAMILIES) {
  const blocks = parseBlocks(await css2(fam.url));
  const latin = blocks.filter(b => b.subset === 'latin');
  if (latin.length === 0) throw new Error('no latin blocks for ' + fam.css);
  for (const b of latin) {
    const buf = await bin(b.url);
    bytes += buf.length;
    faces++;
    css += `/* ${fam.css} ${comments[b.weight] || b.weight} (latin) */\n@font-face {\n  font-family: '${fam.css}';\n  font-style: normal;\n  font-weight: ${b.weight};\n  font-display: swap;\n  src: url(data:font/woff2;base64,${buf.toString('base64')}) format('woff2');\n${b.range ? '  unicode-range: ' + b.range + ';\n' : ''}}\n`;
    console.log(`${fam.css} ${b.weight}: ${(buf.length / 1024).toFixed(1)} KB`);
  }
}
writeFileSync('src/styles/00-embedded-fonts.css', css);
console.log(`\nwrote src/styles/00-embedded-fonts.css: ${faces} faces, raw woff2 ${(bytes / 1024).toFixed(1)} KB`);
